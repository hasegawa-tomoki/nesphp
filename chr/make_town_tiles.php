// ---------------------------------------------------------------------------
// 変換
// ---------------------------------------------------------------------------
function encodeTile(array $rows16, int $ox, int $oy): string
{
    $bp0 = '';
    $bp1 = '';
    for ($y = 0; $y < 8; $y++) {
        $row = $rows16[$oy + $y];
        $b0 = 0;
        $b1 = 0;
        for ($x = 0; $x < 8; $x++) {
            $c = (int) $row[$ox + $x];
            $b0 = ($b0 << 1) | ($c & 1);
            $b1 = ($b1 << 1) | (($c >> 1) & 1);
        }
        $bp0 .= chr($b0);
        $bp1 .= chr($b1);
    }
    return $bp0 . $bp1;
}

function validate(string $name, array $rows): void
{
    if (count($rows) !== 16) {
        throw new RuntimeException("$name: 16 rows required, got " . count($rows));
    }
    foreach ($rows as $i => $r) {
        if (!preg_match('/^[0-3]{16}$/', $r)) {
            throw new RuntimeException("$name: row $i must be 16 chars of 0-3: '$r'");
        }
    }
}

// メタタイルを set に書き込み、[name => baseTile] を返す
function placeMetatiles(string &$chr, int $set, int $baseTile, array $defs): array
{
    $map = [];
    $tile = $baseTile;
    foreach ($defs as $name => [$pal, $rows]) {
        validate($name, $rows);
        if ($tile + 3 > 0xFF) {
            throw new RuntimeException("$name: out of tiles (set $set)");
        }
        $map[$name] = $tile;
        $i = 0;
        foreach ([[0, 0], [8, 0], [0, 8], [8, 8]] as [$ox, $oy]) {
            $off = $set * SET_SIZE + ($tile + $i) * 16;
            $chr = substr_replace($chr, encodeTile($rows, $ox, $oy), $off, 16);
            $i++;
        }
        $tile += 4;
    }
    return $map;
}

